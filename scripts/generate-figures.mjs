function normalizeId(id) {
  return id.replace(/\s+/g, '')
}

function main() {
  const combined = [...RAW, ...MORE].filter((row) => !PLACEHOLDER_IDS.has(row[0]))
  const seen = new Set()
  const unique = []
  for (const row of combined) {
    const id = normalizeId(row[0])
    if (seen.has(id)) continue
    seen.add(id)
    unique.push([id, ...row.slice(1)])
  }

  if (unique.length < 100) {
    console.error(`Only ${unique.length} figures, need 100`)
    process.exit(1)
  }

  const figures = unique.slice(0, 100)
  const traitKeys = [
    'creativity',
    'resilience',
    'wisdom',
    'courage',
    'empathy',
    'discipline',
    'exploration',
    'expression',
    'aesthetics',
    'pragmatism',
  ]

  const lines = []
  lines.push(`import type { TraitVector } from './traits'`)
  lines.push('')
  lines.push(`export type FigureId =`)
  figures.forEach((row, index) => {
    const suffix = index === figures.length - 1 ? '' : ''
    lines.push(`  | '${row[0]}'${suffix}`)
  })
  lines.push('')
  lines.push(`export type Figure = {`)
  lines.push(`  id: FigureId`)
  lines.push(`  name: string`)
  lines.push(`  era: string`)
  lines.push(`  title: string`)
  lines.push(`  tagline: string`)
  lines.push(`  strengths: string[]`)
  lines.push(`  portrait: string`)
  lines.push(`  advice: string`)
  lines.push(`  shareLine: string`)
  lines.push(`  accent: string`)
  lines.push(`  traits: TraitVector`)
  lines.push(`}`)
  lines.push('')
  lines.push(`/** 100 位历史人物：偏重皇帝与诗人，其余为广为人知的名士；文案一律正面 */`)
  lines.push(`export const FIGURE_LIST: Figure[] = [`)

  figures.forEach((row, index) => {
    const [id, name, era, title, tagline, strengths, portrait, advice, shareLine, traits] = row
    const accent = ACCENTS[index % ACCENTS.length]
    const traitObj = traitKeys.map((k, i) => `    ${k}: ${traits[i]},`).join('\n')
    lines.push(`  {`)
    lines.push(`    id: '${id}',`)
    lines.push(`    name: '${name}',`)
    lines.push(`    era: '${era}',`)
    lines.push(`    title: '${title}',`)
    lines.push(`    tagline: '${tagline}',`)
    lines.push(`    strengths: ${JSON.stringify(strengths)},`)
    lines.push(`    portrait: '${portrait}',`)
    lines.push(`    advice: '${advice}',`)
    lines.push(`    shareLine: '${shareLine}',`)
    lines.push(`    accent: '${accent}',`)
    lines.push(`    traits: {`)
    lines.push(traitObj)
    lines.push(`    },`)
    lines.push(`  },`)
  })

  lines.push(`]`)
  lines.push('')
  lines.push(`export const FIGURES: Record<FigureId, Figure> = Object.fromEntries(`)
  lines.push(`  FIGURE_LIST.map((figure) => [figure.id, figure]),`)
  lines.push(`) as Record<FigureId, Figure>`)
  lines.push('')

  const out = path.join(__dirname, '../src/data/figures.ts')
  fs.writeFileSync(out, lines.join('\n'), 'utf8')
  console.log(`Wrote ${figures.length} figures -> ${out}`)

  const emperors = figures.filter((f) =>
    /帝|祖|宗|后|始皇|天子|武王|康熙|雍正|乾隆|顺治|武则天|吕后|慈禧|刘邦|刘备|曹操|孙权|项羽|赵匡胤|朱元璋|杨坚|李渊|李世民/.test(
      f[1] + f[3],
    ),
  )
  const poets = figures.filter((f) =>
    /诗|词|文坛|词客|词骨|词意|词情|诗心|诗魂|诗骨|诗怀|诗思|词中|红楼梦|奇幻|演义|才子|板桥|白石|齐白石|纳兰|屈原|陶渊明|曹植|李煜|柳永|秦观/.test(
      f[3] + f[1],
    ),
  )
  console.log('Rough emperor-related:', emperors.length)
  console.log('Rough poet-related:', poets.length)
}

main()
